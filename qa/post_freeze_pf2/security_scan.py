"""Security hygiene scan of the files PF-2 adds or changes: no embeddings or caches, no extraction dumps, no absolute local
paths, no credentials, no personal files, no RAR archive, no held or rejected documents, no AI attribution.

    python -X utf8 qa/post_freeze_pf2/security_scan.py <repo> [paths...]      (default: git status + untracked files)
"""
import os
import re
import subprocess
import sys

REPO = os.path.abspath(sys.argv[1])
os.chdir(REPO)
paths = sys.argv[2:]
tracked_modified = set()
if not paths:
    out = subprocess.run(["git", "status", "--porcelain", "--untracked-files=all"], capture_output=True, text=True, check=True).stdout
    for line in out.splitlines():
        if not line.strip():
            continue
        rel = line[3:].strip().strip('"').replace("\\", "/")
        paths.append(rel)
        if line[:2].strip() != "??":
            tracked_modified.add(rel)


def added_lines(rel):
    """The lines this change adds to a tracked file (unified diff, no context): pre-existing fixtures are not re-scanned."""
    diff = subprocess.run(["git", "diff", "-U0", "--", rel], capture_output=True, text=True, encoding="utf-8", errors="replace").stdout
    out, line_no = [], 0
    for line in diff.splitlines():
        if line.startswith("@@"):
            m = re.search(r"\+(\d+)", line)
            line_no = int(m.group(1)) - 1 if m else 0
        elif line.startswith("+") and not line.startswith("+++"):
            line_no += 1
            out.append((line_no, line[1:]))
    return out

FORBIDDEN_FILES = [
    (re.compile(r"\.(npy|npz|faiss|pkl|pickle|bin|safetensors)$", re.I), "embedding, index or model binary"),
    (re.compile(r"(^|/)cache/", re.I), "cache folder"),
    (re.compile(r"\.rar$", re.I), "RAR archive"),
    (re.compile(r"\.env($|\.)", re.I), "environment file"),
    (re.compile(r"appraisal", re.I), "held Internal Use document"),
    (re.compile(r"(student|vendor|mcgraw|coursera|akindi|docusign)", re.I), "rejected student or vendor document"),
    (re.compile(r"\.(docx|pptx|xlsx)$", re.I), "office document (not an approved pilot source)"),
]
FORBIDDEN_TEXT = [
    (re.compile(r"[A-Za-z]:\\\\?Users\\\\?|/c/Users/|C:/Users/", re.I), "absolute local path"),
    (re.compile(r"gsk_[A-Za-z0-9]{10,}|sk-[A-Za-z0-9]{20,}|AKIA[0-9A-Z]{16}"), "API key pattern"),
    (re.compile(r"GROQ_API_KEY\s*=\s*['\"]?[A-Za-z0-9_\-]{8,}"), "credential assignment"),
    (re.compile(r"Co-Authored-By|Generated with|Generated by Claude|Claude Code|Anthropic", re.I), "AI attribution"),
    (re.compile(r"Tutorials files", re.I), "local source folder name"),
    (re.compile(r"[A-Za-z0-9._%+-]+@(gmail|yahoo|hotmail|outlook)\.com", re.I), "personal e-mail"),
]
TEXT_EXT = (".py", ".json", ".jsonl", ".md", ".txt", ".csv", ".ini", ".cfg", ".toml", ".yaml", ".yml", ".html", ".sh")
ALLOWLIST_TEXT = {
    # the scan's own patterns and the fixtures that already lived in the tree
    os.path.normpath("qa/post_freeze_pf2/security_scan.py"),
}

problems = []
checked = 0
for rel in paths:
    rel = rel.replace("\\", "/")
    if not os.path.exists(rel) or os.path.isdir(rel):
        continue
    checked += 1
    for pattern, why in FORBIDDEN_FILES:
        if pattern.search(rel):
            problems.append((rel, "file", why))
    if rel.lower().endswith(TEXT_EXT) and os.path.normpath(rel) not in ALLOWLIST_TEXT:
        if rel in tracked_modified:
            lines = added_lines(rel)
            scope = "added line"
        else:
            try:
                text = open(rel, encoding="utf-8", errors="replace").read()
            except OSError as exc:
                problems.append((rel, "read", str(exc)))
                continue
            lines = list(enumerate(text.splitlines(), 1))
            scope = "line"
        for number, line in lines:
            for pattern, why in FORBIDDEN_TEXT:
                m = pattern.search(line)
                if m:
                    problems.append((rel, "%s %d" % (scope, number), "%s: %r" % (why, m.group(0)[:60])))
    size = os.path.getsize(rel)
    if size > 15_000_000:
        problems.append((rel, "size", "%d bytes" % size))

print("checked %d files" % checked)
for rel, where, why in problems:
    print("PROBLEM %-60s %-14s %s" % (rel, where, why))
print("problems:", len(problems))
sys.exit(1 if problems else 0)
